#firstly, we are making a 100*100 grid, then we are making the 2d a 1d array of length 100^2
def make_grid(n=100):
    xs = torch.linspace(0, 1, n) #for the width
    ys = torch.linspace(0, 1, n) #for the height
    gx, gy = torch.meshgrid(xs, ys, indexing="ij") #gx and gy give the x and y cordinate respectively, ij for axis conversion row=x axis
    grid = torch.stack([gx.flatten(), gy.flatten()], dim=1)
    return grid

GRID = make_grid(100)

#sum of the light in the entire room from all the lamp posts at every location on the grid
def brightness(lamps, grid, sigma=0.25):
    """
    lamps: (K, 2) tensor of lamp positions
    grid:  (N, 2) tensor of room points
    returns: (N,) total brightness at each grid point
    """
    #this to get the  pairwise squared distances between every grid point and every lamp
    diff = grid.unsqueeze(1) - lamps.unsqueeze(0)      # each room point is given its own row, each lamp is given its own row, in the shape N, 1, 2
    #this to get the pairwise squared distances between every grid point and every lamp
    #now, next line gives ||p - l||^2 for every (grid point, lamp) pair
    sq_dist = (diff ** 2).sum(dim=2)                    #(N, K)
    B = torch.exp(-sq_dist / (2 * sigma ** 2))          #(N, K) Gaussian brightness per point-lamp pair
    return B.sum(dim=1)                                 # (N, total brightness at a point
#this is to calculate the pairwise exponential proximity penalty
def repulsion(lamps, rho=0.20):
    K = lamps.shape[0]
    total = 0.0
    for i in range(K):
        for j in range(i + 1, K): #for each unique lamp pair
            d2 = ((lamps[i] - lamps[j]) ** 2).sum()
            total = total + torch.exp(-d2 / (2 * rho ** 2))
    return total
#gives net target, its the avg brightness-penalty
def objective(lamps, grid, sigma=0.25, rho=0.20, lam=1.0):
    avg_brightness = brightness(lamps, grid, sigma).mean()
    R = repulsion(lamps, rho)#total clustering penalty
    return avg_brightness - lam * R

def optimize_lamps(n_lamps=3, sigma=0.25, rho=0.20, lam=1.0,
                   steps=300, lr=0.05, seed=42):
    torch.manual_seed(seed)  #fixing randomness for reproducability

    #random parameters wich will get updated later
    raw_lamps = torch.randn(n_lamps, 2, requires_grad=True)
    optimizer = torch.optim.Adam([raw_lamps], lr=lr)

    # scales everything to between 1 and 0
    get_lamps = lambda: torch.sigmoid(raw_lamps)

    init_lamps = get_lamps().detach().clone() #starting points for comparison
    history = [init_lamps] #to store all the positions moved
    J_history = [] #to store the intensities

    for step in range(steps):
        optimizer.zero_grad() #claer gradients from prev steps

        #raw value becomes bounded to 0,1
        current_lamps = get_lamps()
        J = objective(current_lamps, GRID, sigma, rho, lam)
        loss = -J
        loss.backward()
        optimizer.step() #update raw_lamps in the direction that increases J

        #saving the bounded positions
        history.append(current_lamps.detach().clone())
        J_history.append(J.item())

    final_lamps = get_lamps().detach()
    return init_lamps, final_lamps, history, J_history

