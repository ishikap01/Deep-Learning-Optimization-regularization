import numpy as np

def lr_constant(t, eta0=0.002, **kwargs):
    """Constant learning rate: η_t = η0"""
    return eta0


def lr_step_decay(t, eta0=0.002, K=200, **kwargs):
    """Step decay: η_t = η0 * 0.1^(floor(t / K))"""
    return eta0 * (0.1 ** (t // K))


def lr_exponential_decay(t, eta0=0.002, gamma=0.995, **kwargs):
    """Exponential decay: η_t = η0 * gamma^t"""
    return eta0 * (gamma ** t)


def lr_cosine_annealing(t, eta0=0.002, eta_min=1e-5, T=1000, **kwargs):
    """Cosine annealing: η_t = η_min + 0.5*(η0 - η_min)*(1 + cos(π t / T))"""
    return eta_min + 0.5 * (eta0 - eta_min) * (1 + np.cos(np.pi * t / T))


def lr_warmup_cosine_decay(t, eta0=0.002, eta_min=1e-5, T=1000, T_warmup=100, **kwargs):
    """Linear warmup + cosine decay."""
    if t <= T_warmup:
        # Linear warmup from 0 to eta0
        return (t / T_warmup) * eta0
    else:
        # Cosine decay from eta0 to eta_min over [T_warmup, T]
        return eta_min + 0.5 * (eta0 - eta_min) * (
            1 + np.cos(np.pi * (t - T_warmup) / (T - T_warmup))
        )


