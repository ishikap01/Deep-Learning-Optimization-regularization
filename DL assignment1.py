def evaluate_performance(traj, surface_name):
    if surface_name in ['Bowl', 'Ravine']:
        dists = np.linalg.norm(traj, axis=1)
        converged = np.any(dists < 0.1)
        steps = np.argmax(dists < 0.1) if converged else 1000
        # FIX: Dynamically set the status string based on convergence
        status = "Reached Min" if converged else "Did Not Converge"
        return status, steps if converged else ">1000"
    else:  # Saddle
        # FIX: Start point is (-1.5, 0.001). The x-coordinate is already at -1.5,
        # so checking if |x| > 0.5 triggers on step 0. We must only check the y-axis
        # (the unstable direction) to see if it actually falls off the saddle.
        threshold = 0.1
        escaped = np.any(np.abs(traj[:, 1]) > threshold)
        if escaped:
            steps = np.argmax(np.abs(traj[:, 1]) > threshold)
            status = "Escaped"
        else:
            steps = 1000
            status = "Stuck"
        return status, steps if escaped else ">1000"

